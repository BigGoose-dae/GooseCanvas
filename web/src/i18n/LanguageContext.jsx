const LanguageContext = createContext(null);

function getInitialLanguage() {
  return preferredLanguage(
    localStorage.getItem("goose-canvas-language"),
    navigator.language,
  );
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(getInitialLanguage);

  useEffect(() => {
    document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
    document.title = language === "zh" ? "Goose Canvas · AI 创作画布" : "Goose Canvas · AI Creation Canvas";
    localStorage.setItem("goose-canvas-language", language);
  }, [language]);

  const value = useMemo(() => ({
    language,
    locale: language === "zh" ? "zh-CN" : "en-US",
    setLanguage,
    toggleLanguage: () => setLanguage((current) => current === "zh" ? "en" : "zh"),
    t: (key, params = {}) => {
      const value = messages[language][key] ?? messages.zh[key] ?? key;
      return typeof value === "function" ? value(params) : value;
    },
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("useLanguage must be used inside LanguageProvider");
  return value;
}
